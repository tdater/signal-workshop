// Writes the list of published project slugs for the feedback API, which can't read the content
// collections at runtime. Runs before every build; tests fail if it's stale.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { parse } from 'yaml';

const dir = new URL('../src/content/projects/', import.meta.url);
const slugs = readdirSync(dir)
  .filter((f) => f.endsWith('.yaml'))
  .map((f) => parse(readFileSync(new URL(f, dir), 'utf8')))
  .filter((p) => p.published)
  .map((p) => p.slug)
  .sort();
const out = `// Generated by scripts/sync-projects.mjs. Do not edit.\nexport const PROJECT_IDS: readonly string[] = ${JSON.stringify(slugs)};\n`;
writeFileSync(new URL('../functions/_lib/project-ids.ts', import.meta.url), out);
console.log('project ids:', slugs.join(', '));
